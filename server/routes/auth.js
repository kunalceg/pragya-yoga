// 🔑 FORGOT PASSWORD
// ==========================================
router.post("/forgot-password", async (req, res) => {
  try {
    const { email } = req.body;
    const user = await User.findOne({ email });
    if (!user) return res.status(400).json({ error: "User not found" });

    const token = jwt.sign({ id: user._id }, process.env.JWT_SECRET, { expiresIn: "15m" });
    const resetLink = `http://localhost:5173/reset-password/${token}`;

    await transporter.sendMail({
      from: process.env.EMAIL_USER,
      to: email,
      subject: "Password Reset Request",
      text: `Reset link: ${resetLink}`
    });

    res.json({ msg: "Reset link sent." });
  } catch (err) {
    console.error("Forgot password error:", err);
    res.status(500).json({ error: "Server error" });
  }
});

// ==========================================
// 👤 GET PROFILE
// ==========================================
router.get("/profile", authMiddleware, async (req, res) => {
  try {
    const user = await User.findById(req.user.id).select("-password");
    if (!user) return res.status(404).json({ error: "User not found" });
    res.json(user);
  } catch (err) {
    console.error("Get profile error:", err);
    res.status(500).json({ error: "Server error" });
  }
});

// ==========================================
// ✏️ UPDATE PROFILE
// ==========================================
router.put("/profile", authMiddleware, async (req, res) => {
  try {
    const { name, email, phone, city, style, level, newPassword } = req.body;

    const updatedFields = {};
    if (name  !== undefined) updatedFields.name  = name;
    if (phone !== undefined) updatedFields.phone = phone;
    if (city  !== undefined) updatedFields.city  = city;
    if (style !== undefined) updatedFields.style = style;
    if (level !== undefined) updatedFields.level = level;

    if (newPassword && newPassword.trim() !== "") {
      const salt = await bcrypt.genSalt(10);
      updatedFields.password = await bcrypt.hash(newPassword, salt);
    }

    if (email !== undefined) {
      const emailOwner = await User.findOne({ email });
      if (emailOwner && emailOwner._id.toString() !== req.user.id) {
        return res.status(400).json({ error: "Email is already in use by another account" });
      }
      updatedFields.email = email;
    }

    const updatedUser = await User.findByIdAndUpdate(
      req.user.id,
      { $set: updatedFields },
      { new: true, runValidators: true }
    ).select("-password");

    if (!updatedUser) return res.status(404).json({ error: "User not found" });

    res.json(updatedUser);
  } catch (err) {
    console.error("Profile update error:", err);
    res.status(500).json({ error: "Could not update profile" });
  }
});

export { authMiddleware };
export default router;
